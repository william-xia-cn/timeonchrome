'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync('extension/admin/admin.html', 'utf8');
const script = fs.readFileSync('extension/admin/admin.js', 'utf8');
assert.match(html, /data-rules-tab="downtime-management">停用时间/);
const tabs = [...html.matchAll(/data-rules-tab="([^"]+)"/g)].map(match => match[1]).filter(key => ['quota-management','schedule-management','downtime-management','autonomy-management'].includes(key));
assert.deepEqual(tabs, ['quota-management','schedule-management','downtime-management','autonomy-management']);
for (const label of ['正常进入休息网站','限制时段内使用','超出时间配额使用','强行使用提醒','不设时间段累计使用上限','quotaOverrunConfirmationRequired']) assert(script.includes(label));
assert(!html.includes('id="rules-force-limits-card"'));
assert(!script.includes('advisoryWindowDailyMaxMinutes'));
assert(script.includes('旧配置记录（兼容执行，只读）'));
console.log('forced-use-admin-readonly: passed');
